"""Build a self-contained WASM (Pyodide) export of notebooks/demo.py.

Pyodide can't pip-install this local package, so the library and my_ops sources are
embedded in the first cell and written to the in-browser filesystem at startup.

    uv run python scripts/build_wasm.py   # -> dist/wasm/index.html
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
pkg = ROOT / "src" / "anything_analyzer"
files = {f"anything_analyzer/{p.name}": p.read_text() for p in sorted(pkg.glob("*.py"))}
files["my_ops.py"] = (ROOT / "notebooks" / "my_ops.py").read_text()

nb = (ROOT / "notebooks" / "demo.py").read_text()
old_imports = """    from anything_analyzer import OpPanel, Param, Pipeline, chain_view, mode_toggle, preview
    import my_ops
"""
assert old_imports in nb, "demo.py import block changed; update build_wasm.py"
bootstrap = f"""    import importlib, pathlib, sys
    # Embedded sources (generated by scripts/build_wasm.py).
    _root = pathlib.Path("/tmp/anything_analyzer_src")
    for _name, _code in {files!r}.items():
        _p = _root / _name
        _p.parent.mkdir(parents=True, exist_ok=True)
        _p.write_text(_code)
    sys.path.insert(0, str(_root))
    _aa = importlib.import_module("anything_analyzer")
    my_ops = importlib.import_module("my_ops")
    OpPanel, Param, Pipeline = _aa.OpPanel, _aa.Param, _aa.Pipeline
    chain_view, mode_toggle, preview = _aa.chain_view, _aa.mode_toggle, _aa.preview
"""
nb = nb.replace(old_imports, bootstrap)
out_nb = ROOT / "dist" / "demo_wasm.py"
out_nb.parent.mkdir(exist_ok=True)
out_nb.write_text(nb)
mode = sys.argv[1] if len(sys.argv) > 1 else "run"
subprocess.run(
    ["marimo", "export", "html-wasm", str(out_nb), "-o", str(ROOT / "dist" / "wasm" / "index.html"), "--single-file", "--mode", mode, "--show-code", "-f"],
    check=True,
)
print("built", ROOT / "dist" / "wasm")
